import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const version = fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim();
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Invalid VERSION');
const tag = 'v' + version.replace(/\.0$/, '');
const check = process.argv.includes('--check');
function update(file, content) {
  const target = path.join(root, file);
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === content) return;
  if (check) throw new Error('Version drift: ' + file);
  fs.writeFileSync(target, content);
}
function json(file, mutate) {
  const obj = JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  mutate(obj); update(file, JSON.stringify(obj, null, 2) + '\n');
}
json('frontend/package.json', obj => { obj.version = version; });
json('frontend/package-lock.json', obj => { obj.version = version; obj.packages[''].version = version; });
json('backend/cmd/castorice/winres/winres.json', obj => {
  obj.RT_MANIFEST['#1']['0409'].identity.version = version + '.0';
  const r = obj.RT_VERSION['#1']['0000'];
  r.fixed.file_version = r.fixed.product_version = version + '.0';
  r.info['0804'].ProductVersion = version; r.info['0804'].FileVersion = version + '.0';
});
update('backend/internal/model/version.go', `// Code generated by scripts/sync-version.mjs; DO NOT EDIT.\npackage model\n\nconst Version = "${tag}"\n`);
update('frontend/src/version.ts', `// Code generated by scripts/sync-version.mjs; DO NOT EDIT.\nexport const APP_VERSION = "${tag}";\n`);
